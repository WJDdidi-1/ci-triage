// Shell completion scripts for ci-triage, generated from the same
// option list the parser uses — so a new flag can never be
// completable but unparseable (or parseable but uncompletable)
// without a test failing. ripgrep ships static scripts in complete/;
// generating them on demand from the spec is the same idea without
// the drift: there is no static copy to go stale. The bin derives
// KNOWN_OPTIONS from this spec, so the spec is the single source of
// truth; the --help text is checked against it in
// test/completion.test.mjs.
//
// Usage: ci-triage completion <bash|zsh|fish>
// Install, e.g.: ci-triage completion bash > ~/.bash_completion.d/ci-triage

export const SHELLS = ['bash', 'zsh', 'fish'];

// Short descriptions, shown by zsh and fish next to the name.
export const COMMAND_DESCRIPTIONS = {
  completion: 'Print a shell completion script',
  doctor: 'Check that ci-triage is set up correctly',
};

export const OPTION_DESCRIPTIONS = {
  '--runs': 'failed runs to examine',
  '--workflow': 'only this workflow',
  '--branch': 'only this branch',
  '--json': 'machine-readable output',
  '-j': 'machine-readable output',
  '--top': 'show only the N highest-ranked root causes',
  '--report': 'also write this triage as a Markdown report file',
  '--annotations': 'emit GitHub Actions workflow-command annotations',
  '--mcp': 'serve the triage as an MCP server',
  '--skill-generate': 'write a Claude Agent Skills SKILL.md',
  '--global': 'write the skill to ~/.claude/skills',
  '--project': 'write the skill to ./.claude/skills',
  '--help': 'show this help',
  '-h': 'show this help',
  '--version': 'print the version',
  '-v': 'print the version',
};

// ci-triage takes a repo, not a subcommand, so every option is a
// global option. `completion` is the one pseudo-command: its first
// argument is a shell name, handled specially by the generators.
export const GLOBAL_OPTIONS = [
  '--runs', '--workflow', '--branch', '--json', '-j', '--top', '--report',
  '--annotations',
  '--mcp', '--skill-generate', '--global', '--project', '--help', '-h',
  '--version', '-v',
];

// Value-taking options, and what zsh should complete for their value:
// '' means a plain value (no completion), '_files' a file.
export const VALUE_COMPLETIONS = {
  '--runs': '',
  '--workflow': '',
  '--branch': '',
  '--top': '',
  '--report': '_files',
};

export const VALUE_OPTIONS = new Set(Object.keys(VALUE_COMPLETIONS));

export function knownCommands() {
  return Object.keys(COMMAND_DESCRIPTIONS);
}

export function knownOptions() {
  return [...GLOBAL_OPTIONS].sort();
}

// Returns the script for `shell`, or null for an unknown shell.
export function generateCompletion(shell) {
  if (shell === 'bash') return bashScript();
  if (shell === 'zsh') return zshScript();
  if (shell === 'fish') return fishScript();
  return null;
}

function escapeSingleQuotes(text) {
  return text.replace(/'/g, "'\\''");
}

function bashScript() {
  const globalOpts = GLOBAL_OPTIONS.join(' ');
  const valueOpts = [...VALUE_OPTIONS].join('|');
  return `# bash completion for ci-triage. Generated by \`ci-triage completion bash\`.
# Install: ci-triage completion bash > ~/.bash_completion.d/ci-triage
# or: source <(ci-triage completion bash)
_ci_triage() {
  local cur prev
  cur="\${COMP_WORDS[COMP_CWORD]}"
  prev="\${COMP_WORDS[COMP_CWORD-1]}"
  # After a value-taking option, complete filenames (the -o default
  # below) instead of option names.
  case "$prev" in
    ${valueOpts}) return 0 ;;
  esac
  # The completion command takes a shell name.
  if [[ "\${COMP_WORDS[1]}" == "completion" ]]; then
    COMPREPLY=( $(compgen -W "${SHELLS.join(' ')}" -- "$cur") )
    return 0
  fi
  if [[ "$cur" == -* ]]; then
    COMPREPLY=( $(compgen -W "${globalOpts}" -- "$cur") )
    return 0
  fi
  if [[ $COMP_CWORD -eq 1 ]]; then
    COMPREPLY=( $(compgen -W "completion doctor ${globalOpts}" -- "$cur") )
    return 0
  fi
  return 0
}
complete -o default -F _ci_triage ci-triage
`;
}

// One _arguments spec per option: '--json[description]' for a flag,
// '--top[description]:N:' for a value with no completion,
// '--report[description]:file:_files' for a file value.
function zshOptSpec(option) {
  const description = OPTION_DESCRIPTIONS[option] ?? '';
  if (!VALUE_OPTIONS.has(option)) return `'${option}[${description}]'`;
  const completion = VALUE_COMPLETIONS[option];
  const label = option === '--top' || option === '--runs' ? 'N' : option === '--report' ? 'file' : 'value';
  return completion
    ? `'${option}[${description}]:${label}:${completion}'`
    : `'${option}[${description}]:${label}:'`;
}

function zshScript() {
  const globalSpecs = GLOBAL_OPTIONS.map((option) => `    ${zshOptSpec(option)} \\`).join('\n');
  return `#compdef ci-triage
# zsh completion for ci-triage. Generated by \`ci-triage completion zsh\`.
# Install: ci-triage completion zsh > ~/.zsh/completions/_ci-triage
# (and make sure ~/.zsh/completions is on your fpath before compinit)
_ci_triage() {
  local -a commands
  commands=(
    'completion:Print a shell completion script'
    'doctor:Check that ci-triage is set up correctly'
  )
  _arguments -C \\
${globalSpecs}
    '1: :->first' \\
    '*:: :->rest' \\
    && return 0
  case "$state" in
    first)
      _describe -t commands 'ci-triage command' commands
      ;;
    rest)
      case "$line[1]" in
        completion) _arguments '1:shell:(bash zsh fish)' ;;
      esac
      ;;
  esac
}
_ci_triage "$@"
`;
}

function fishScript() {
  const lines = [
    '# fish completion for ci-triage. Generated by `ci-triage completion fish`.',
    '# Install: ci-triage completion fish > ~/.config/fish/completions/ci-triage.fish',
  ];
  lines.push(`complete -c ci-triage -n '__fish_use_subcommand' -a 'completion' -d '${escapeSingleQuotes(COMMAND_DESCRIPTIONS.completion)}'`);
  lines.push(`complete -c ci-triage -n '__fish_use_subcommand' -a 'doctor' -d '${escapeSingleQuotes(COMMAND_DESCRIPTIONS.doctor)}'`);
  const noCommand = 'not __fish_seen_subcommand_from completion';
  for (const option of GLOBAL_OPTIONS) {
    lines.push(fishOptLine(option, noCommand));
  }
  lines.push(`complete -c ci-triage -n '__fish_seen_subcommand_from completion' -a 'bash zsh fish' -d 'shell to print completions for'`);
  for (const option of ['--help', '-h', '--version', '-v']) {
    lines.push(fishOptLine(option, '__fish_seen_subcommand_from completion'));
  }
  return `${lines.join('\n')}\n`;
}

function fishOptLine(option, condition) {
  const description = OPTION_DESCRIPTIONS[option] ?? '';
  const flag = option.startsWith('--') ? `-l ${option.slice(2)}` : `-s ${option.slice(1)}`;
  const value = VALUE_OPTIONS.has(option) ? ' -r' : '';
  return `complete -c ci-triage -n '${condition}' ${flag}${value} -d '${escapeSingleQuotes(description)}'`;
}
